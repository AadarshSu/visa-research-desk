# The languages asked of Wikidata: every language a publisher row may name, with Norwegian Bokmål
# under its Wikidata code.
WIKIDATA_LANGUAGES = (
    "ar", "bg", "cs", "da", "de", "en", "es", "fi", "fr", "hr", "hu", "id", "it", "ja", "ko",
    "nb", "nl", "pl", "pt", "ro", "ru", "sk", "sl", "sr", "sv", "th", "zh",
)  # fmt: skip

SOFT_404 = re.compile(
    r"\b404\b|not found|page introuvable|nicht gefunden|no encontrad|niet gevonden"
)


def wikidata_query() -> str:
    """The SPARQL that lists each country's name in every publisher language."""

    languages = ", ".join(f'"{code}"' for code in WIKIDATA_LANGUAGES)
    return (
        "SELECT ?iso ?label WHERE { ?c wdt:P297 ?iso . ?c rdfs:label ?label . "
        f"FILTER(LANG(?label) IN ({languages})) }}"
    )


def names_from_wikidata(
    payload: dict[str, Any], codes: Iterable[str]
) -> dict[str, dict[str, list[str]]]:
    """Each country's names by language, from a Wikidata SPARQL JSON result.

    Several Wikidata items can carry one ISO code (a state and its historical predecessor), so every
    label is kept; matching only ever asks whether a link names one of them.
    """

    wanted = set(codes)
    names: dict[str, dict[str, list[str]]] = {}
    for binding in payload["results"]["bindings"]:
        code = binding["iso"]["value"]
        if code not in wanted:
            continue
        language = binding["label"]["xml:lang"]
        value = binding["label"]["value"]
        bucket = names.setdefault(code, {}).setdefault(language, [])
        if value not in bucket:
            bucket.append(value)
    return {code: dict(sorted(by_language.items())) for code, by_language in sorted(names.items())}


