"""Building each government's checked link per destination, offline (DECISIONS entry 260).

The panel shows a link and nothing else, so the only thing worth building is a link that is right:
this government's page for this destination. Each reviewed row in `advisory_publishers.yaml` says
how to find one — an address pattern, an index read once and matched by the destination's name in
the government's own language, or the government's own published data — and every link found is
**opened before it is written**, as the app fetches: our own user agent, `robots.txt` obeyed, TLS
verified, and a challenge or refusal never worked around. A link that does not open is left out,
and the panel falls back to the government's advice page.

A government that refuses us cannot have its links checked. Its destination links are written only
when its own published data names them (the State Department's JSON); otherwise it gets its advice
page alone.

Destination names come from `country_names.yaml`, generated from Wikidata by `country-names`.
"""

